// Owned isolated browser; fake MIDI only. No physical port enumeration or output.
const {chromium}=require(process.env.PLAYWRIGHT_CORE||'playwright-core')
const {fakeMidi}=require('./e2e-zaq-host.cjs'),assert=require('node:assert/strict')
;(async()=>{const browser=await chromium.launch({headless:true});try{
 const page=await browser.newPage({viewport:{width:1600,height:1000}}),errors=[]
 page.on('pageerror',e=>errors.push(String(e)))
 await page.addInitScript(fakeMidi,{sync:true})
 await page.addInitScript(()=>localStorage.setItem('bcr32-studio.assignment-live','false'))
 await page.goto((process.argv[2]??'http://127.0.0.1:5187')+'/editor/?native=0')
 const knob=page.getByRole('button',{name:'Encoder 8 rotation',exact:true})
 await page.getByRole('button',{name:/^Encoder label 8 /}).click()
 const type=page.getByRole('combobox',{name:'MIDI message type',exact:true})
 await type.selectOption('sysex')
 const pane=page.locator('.custom-program')
 await pane.locator('.custom-advanced > summary').click()
 await page.getByRole('button',{name:'Apply custom program locally',exact:true}).click()
 await page.waitForTimeout(800)
 const custom=()=>page.evaluate(()=>window.__sent.filter(b=>b[0]===240&&b[1]===125))
 assert.deepEqual(await custom(),[],'opening/selection/local apply do not transmit values')
 const toggle=page.getByRole('button',{name:'MIDI → BCR32',exact:true})
 assert.equal(await toggle.getAttribute('aria-pressed'),'true','custom editing keeps value emission enabled')
 const box=await knob.boundingBox(),x=box.x+box.width*.18,y=box.y+box.height*.5
 await page.mouse.move(x,y);await page.mouse.down();await page.mouse.move(x,y-40,{steps:8});await page.mouse.up()
 await page.waitForFunction(()=>window.__sent.some(b=>b.length===4&&b[1]===125&&b[2]===20))
 assert.deepEqual((await custom()).at(-1),[240,125,20,247],'actual mouse drag emits the selected template value')
 await page.getByText('SysEx value sent to BCR32 output.',{exact:true}).waitFor()
 const before=(await custom()).length
 await pane.locator('.custom-preview > summary').click()
 await page.getByRole('slider',{name:'SysEx simulation value',exact:true}).fill('65')
 await page.waitForTimeout(100)
 assert.equal((await custom()).length,before,'simulation remains inert')
 await toggle.click();await knob.focus();await page.keyboard.press('ArrowUp');await page.waitForTimeout(100)
 assert.equal((await custom()).length,before,'disabled MIDI only changes the local value')
 await toggle.click();await page.waitForTimeout(100)
 assert.equal((await custom()).length,before,'enabling cannot replay local values')
 await knob.focus();await page.keyboard.press('ArrowUp')
 await page.waitForFunction(n=>window.__sent.filter(b=>b[1]===125).length>n,before)
 assert.equal((await custom()).at(-1)[2],22,'next explicit gesture emits its current value')
 const received=(await custom()).length
 await page.evaluate(()=>window.__emit([240,125,90,247]));await page.waitForTimeout(100)
 assert.equal((await custom()).length,received,'incoming SysEx never echoes')
 assert.deepEqual(errors,[])
 console.log('PASS browser: encoder8 mouse SysEx, output toggle preserved, exact payload, inert preview/enable/RX and no CC fallback; fake MIDI only')
}finally{await browser.close()}})().catch(e=>{console.error(e);process.exitCode=1})
