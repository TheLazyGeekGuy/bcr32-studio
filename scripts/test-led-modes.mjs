import assert from 'node:assert/strict'
import { build } from 'esbuild'
const result = await build({ entryPoints: [new URL('../src/led-modes.ts', import.meta.url).pathname], bundle: true, write: false, platform: 'node', format: 'esm' })
const { ledModes, ledSegments, validLedMode } = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`)
const lit = (mode, value, ...rest) => ledSegments(mode, value, ...rest).flatMap((on, i) => on ? [i] : [])
assert.equal(ledModes.length, 12)
assert.deepEqual(lit('off', 127), [])
assert.deepEqual(lit('dot', 64), lit('1dot_in', 64))
assert.deepEqual(lit('1dot_in', 0), [0])
assert.deepEqual(lit('1dot_ex', 0), [])
assert.deepEqual(lit('2dot_in', 3), [0, 1])
assert.deepEqual(lit('2dot_in', 127), [20])
assert.deepEqual(lit('2dot_ex', 0), [])
assert.equal(lit('bar', 127).length, 21)
assert.equal(lit('bar_ex', 0).length, 0)
assert.deepEqual(lit('spread', 0), [10])
assert.equal(lit('spread', 127).length, 21)
assert.equal(lit('qual', 0).length, 21)
assert.deepEqual(lit('qual', 127), [10])
assert.deepEqual(lit('pan', 64), [10])
assert.deepEqual(lit('pan', 0), Array.from({ length: 11 }, (_, i) => i))
assert.deepEqual(lit('pan', 127), Array.from({ length: 11 }, (_, i) => i + 10))
assert.equal(lit('cut', 0).length, 21)
assert.deepEqual(lit('cut', 127), [])
assert.deepEqual(lit('damp', 0), [20])
assert.equal(lit('damp', 127).length, 21)
assert.deepEqual(lit('1dot_in', 16383, 0, 16383), [20])
assert.deepEqual(lit('pan', 50, 20, 80), [10])
for (const mode of ledModes) {
  assert.ok(validLedMode(mode))
  assert.deepEqual(lit(mode, 127, 0, 127, false, true), [])
  assert.deepEqual(lit(mode, 127, 0, 127, true, false), [])
  assert.equal(ledSegments(mode, 999).length, 21)
}
assert.equal(validLedMode('unknown'), false)
console.log('PASS: twelve LED modes, endpoints/center/interpolation, 14-bit/custom ranges, OFF/unknown values dark')
