// Isolated browser with fake MIDI only. Never requests physical ports or sends a custom payload.
const {chromium}=require(process.env.PLAYWRIGHT_CORE||'playwright-core')
const {fakeMidi}=require('./e2e-zaq-host.cjs')
const assert=require('node:assert/strict'),fs=require('node:fs')
;(async()=>{
 const browser=await chromium.launch({headless:true})
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];page.on('pageerror',e=>errors.push(String(e)))
  await page.addInitScript(fakeMidi,{sync:true})
  await page.goto((process.argv[2]??'http://127.0.0.1:5187')+'/editor/?native=0')
  const pane=page.locator('.custom-program');await pane.locator('summary').click()
  const group=page.getByRole('group',{name:'Custom program representation'}),template=page.getByRole('textbox',{name:'SysEx template',exact:true})
  await template.fill('F0 42 31 03 41 0F {val} F7')
  await page.getByLabel('BCL maximum',{exact:true}).fill('63')
  assert.equal(await page.getByRole('textbox',{name:'Simulated SysEx output'}).inputValue(),'F0 42 31 03 41 0F 20 F7')
  await template.fill('F0 42 80 F7');assert.equal(await page.getByRole('button',{name:'Apply custom program locally'}).isEnabled(),false)
  assert.match(await page.getByRole('textbox',{name:'Simulated SysEx output'}).inputValue(),/Invalid/)
  await template.fill('F0 42 31 03 41 0F {val} F7')
  await group.getByRole('button',{name:'BCL',exact:true}).click()
  const text=page.getByRole('textbox',{name:'Custom BCL control body'})
  const source='; retained comment\n.minmax 0 63\n.default 0\n.tx $F0 $42 $31 $03 $41 $0F val $F7 ; retained inline\n.showvalue on'
  await text.fill(source);await group.getByRole('button',{name:'SysEx',exact:true}).click();await group.getByRole('button',{name:'BCL',exact:true}).click()
  assert.equal(await text.inputValue(),source,'mode changes preserve comments/source')
  await page.getByRole('button',{name:'Apply custom program locally'}).click()
  assert.equal(await page.locator('.standard-assignment').evaluate(n=>n.disabled),true)
  assert.match(await pane.locator('summary').innerText(),/SYSEX/)
  const save=page.waitForEvent('download');await page.getByRole('button',{name:'Export control BCL',exact:true}).click();const downloaded=await save
  const exported=fs.readFileSync(await downloaded.path(),'utf8');assert.equal(exported,`$rev BCR32\n$encoder 1\n${source}\n$end`)
  await page.waitForTimeout(650);await page.getByRole('button',{name:'Restore standard assignment',exact:true}).click()
  assert.equal(await page.locator('.standard-assignment').evaluate(n=>n.disabled),false)
  await page.getByRole('group',{name:'History',exact:true}).getByRole('button',{name:'Undo',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('.standard-assignment').disabled)
  await page.reload();await page.locator('.custom-program[open]').waitFor()
  await group.getByRole('button',{name:'BCL',exact:true}).click();assert.equal(await text.inputValue(),source,'JSON draft survives a reload')
  const opaque=source+'\n.vendor-extension val0\n.tx $F0 $7D cks-1 2 $F7'
  await text.fill(opaque);await page.getByRole('button',{name:'Apply custom program locally'}).click()
  await group.getByRole('button',{name:'SysEx',exact:true}).click();assert.equal(await template.evaluate(n=>n.readOnly),true)
  await group.getByRole('button',{name:'BCL',exact:true}).click();assert.equal(await text.inputValue(),opaque)
  await group.getByRole('button',{name:'Raw',exact:true}).click();assert.match(await page.getByRole('textbox',{name:'Raw BCL file bytes'}).inputValue(),/^F0 00 20 32 7F 64 20/)
  const wrong='$rev BCR32\n$encoder 2\n.tx $F0 $7D val $F7\n$end'
  await page.getByLabel('Import custom BCL or SYX').setInputFiles({name:'wrong-target.bcl',mimeType:'text/plain',buffer:Buffer.from(wrong)})
  await page.waitForFunction(()=>document.querySelector('.custom-program').textContent.includes('Import not applied'))
  assert.equal(await page.getByRole('button',{name:'Apply custom program locally'}).isEnabled(),false)
  const originalDownload=page.waitForEvent('download');await page.getByRole('button',{name:'Save original import'}).click()
  assert.equal(fs.readFileSync(await (await originalDownload).path(),'utf8'),wrong,'failed import original bytes survive without altering the program')
  const badWrites=await page.evaluate(()=>window.__sent.filter(b=>b[0]!==240||b[1]!==0||b[2]!==32||b[3]!==50||b[6]===32||b[6]===114||b[6]===119||b[6]>=49&&b[6]<=56&&b.length>8))
  assert.deepEqual(badWrites,[],'edits, previews and exports never send custom/standard/OFF/STORE/firmware writes')
  assert.deepEqual(errors,[])
  console.log('PASS BCL/SysEx browser: hex↔BCL, invalid draft refusal, source/comments, selected fragment export, local apply, explicit standard restore, global Undo, reload persistence, opaque/raw views and zero hardware writes')
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
